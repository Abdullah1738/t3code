#!/usr/bin/env bash
set -euo pipefail
umask 022

# Run on the build box with JDK 21; this never installs or selects a live backend.
readonly commit=7954daf7563a69cce9d0b89c8542e40bf46f7c6e
readonly sbt_version=1.12.11
readonly sbt_sha256=b4c0c55d68f11b1510d884641cb1b1456191dac40ddc958bf86c825adc344e16

if [[ $# -gt 1 || ${1:-} == --help ]]; then
  echo "Usage: JAVA_HOME=<jdk21> $0 [new-output-directory]"
  exit 0
fi
[[ $(uname -s) == Linux ]] || { echo 'Build on Linux through offbox.' >&2; exit 1; }
for tool in git curl python3 sha256sum; do command -v "$tool" >/dev/null; done
if [[ -n ${JAVA_HOME:-} ]]; then export PATH="$JAVA_HOME/bin:$PATH"; fi
java -version 2>&1 | head -n 1 | grep -Eq 'version "21[."]' || {
  echo 'JDK 21 is required (set JAVA_HOME).' >&2; exit 1;
}

out=${1:-tmp/apalache-patched-0.62.4}
# Refusing an existing directory avoids overwriting a previous artifact or build.
mkdir -p "$(dirname "$out")"
mkdir "$out"
out=$(cd "$out" && pwd)
exec > >(tee "$out/build.log") 2>&1
java -version
work=$(mktemp -d "${TMPDIR:-/tmp}/apalache-build.XXXXXX")
echo "Build source: $work/source"
git clone --no-checkout https://github.com/apalache-mc/apalache.git "$work/source"
cd "$work/source"
git checkout --detach "$commit"
[[ $(git rev-parse 'v0.62.4^{commit}') == "$commit" ]]
[[ $(cat project/build.properties) == "sbt.version=$sbt_version" ]]
epoch=$(git show -s --format=%ct HEAD)
export SOURCE_DATE_EPOCH=$epoch TZ=UTC LC_ALL=C

# 1.75.0 is the first non-downgrade release with reflection generated by >=3.25.6.
# Its published v1alpha and v1 sources identify protoc 3.25.8. Keep ScalaPB 0.11.20.
cat > patched-backend.sbt <<'SBT'
ThisBuild / dependencyOverrides ++= Seq(
  "grpc-api", "grpc-core", "grpc-context", "grpc-netty", "grpc-util",
  "grpc-stub", "grpc-protobuf", "grpc-protobuf-lite", "grpc-services"
).map("io.grpc" % _ % "1.75.0") ++ Seq(
  "com.google.protobuf" % "protobuf-java" % "3.25.8",
  "com.google.protobuf" % "protobuf-java-util" % "3.25.8"
)
ThisBuild / PB.protocVersion := "3.25.8"

lazy val verifyPatchedDependencies = taskKey[Unit]("Check the resolved backend dependencies")
verifyPatchedDependencies := {
  val reports = Seq(
    ("root/Runtime", "runtime", (Runtime / update).value),
    ("shai/Compile", "compile", (LocalProject("shai") / Compile / update).value)
  )
  reports.foreach { case (scope, configuration, report) =>
    val resolved = report.configurations.find(_.configuration.name == configuration)
      .getOrElse(sys.error(s"Missing $configuration configuration in $scope"))
    val modules = resolved.modules.filterNot(_.evicted)
      .map(_.module).filter(m => Set("io.grpc", "com.google.protobuf")(m.organization))
      .map(m => (m.organization, m.name, m.revision)).distinct.sorted
    modules.foreach { case (org, name, version) =>
      println(s"PATCHED_DEP $scope $org:$name:$version")
      require(version == (if (org == "io.grpc") "1.75.0" else "3.25.8"),
        s"Unexpected dependency: $org:$name:$version")
    }
    val grpc = modules.filter(_._1 == "io.grpc").map(_._2).toSet
    require(Set("grpc-api", "grpc-core", "grpc-netty", "grpc-util", "grpc-stub",
      "grpc-protobuf", "grpc-protobuf-lite", "grpc-services").subsetOf(grpc),
      s"Missing gRPC dependencies in $scope: $grpc")
    require(modules.exists(m => m._1 == "com.google.protobuf" && m._2 == "protobuf-java"))
  }
}
SBT
cp patched-backend.sbt "$out/overrides.sbt"
curl --fail --location --retry 3 --output "$out/sbt-launch.jar" \
  "https://repo.maven.apache.org/maven2/org/scala-sbt/sbt-launch/$sbt_version/sbt-launch-$sbt_version.jar"
printf '%s  %s\n' "$sbt_sha256" "$out/sbt-launch.jar" | sha256sum --check
java -Xms256m -Xmx6g -Dsbt.supershell=false -Dsbt.log.noformat=true \
  -jar "$out/sbt-launch.jar" verifyPatchedDependencies \
  'set Universal / packageName := "apalache"' 'Universal/packageZipTarball' | tee "$out/sbt.log"
grep '^PATCHED_DEP ' "$out/sbt.log" > "$out/dependencies.txt"

# Native packager supplies the release layout; normalize archive metadata so the
# same inputs produce the same tarball rather than carrying the build clock/UID.
python3 - "$out" "$epoch" "$work/source" <<'PY'
import gzip, hashlib, io, json, pathlib, sys, tarfile, zipfile
out = pathlib.Path(sys.argv[1])
epoch = int(sys.argv[2])
source = pathlib.Path(sys.argv[3]) / 'target/universal/apalache.tgz'
artifact = out / 'apalache-0.62.4-grpc-1.75.0.tgz'
with tarfile.open(source, 'r:gz') as src, artifact.open('wb') as raw:
    with gzip.GzipFile(filename='', mode='wb', fileobj=raw, mtime=0) as compressed:
        with tarfile.open(fileobj=compressed, mode='w', format=tarfile.GNU_FORMAT) as dst:
            for member in sorted(src.getmembers(), key=lambda m: m.name):
                member.mtime = epoch
                member.uid = member.gid = 0
                member.uname = member.gname = ''
                member.pax_headers = {}
                data = src.extractfile(member) if member.isfile() else None
                if member.name == 'apalache/lib/apalache.jar':
                    normalized = io.BytesIO()
                    # ZIP seeks backwards; materialize once to avoid repeatedly
                    # decompressing the enclosing tar.gz for each class entry.
                    with zipfile.ZipFile(io.BytesIO(data.read())) as jar, zipfile.ZipFile(
                        normalized, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9
                    ) as target:
                        request = 'io/grpc/reflection/v1alpha/ServerReflectionRequest.class'
                        if request not in jar.namelist():
                            raise RuntimeError('Missing v1alpha reflection request')
                        for entry in sorted(jar.infolist(), key=lambda e: e.filename):
                            contents = jar.read(entry)
                            if entry.filename.startswith('io/grpc/reflection/') and \
                                    entry.filename.endswith('.class') and \
                                    b'makeExtensionsImmutable' in contents:
                                raise RuntimeError(f'Unsafe reflection gencode: {entry.filename}')
                            entry.date_time = (2010, 1, 1, 0, 0, 0)
                            entry.extra = b''
                            entry.create_system = 3
                            target.writestr(entry, contents, compress_type=zipfile.ZIP_DEFLATED,
                                            compresslevel=9)
                    data = io.BytesIO(normalized.getvalue())
                    member.size = len(data.getvalue())
                dst.addfile(member, data)
sha = hashlib.sha256(artifact.read_bytes()).hexdigest()
(out / 'SHA256SUMS').write_text(f'{sha}  {artifact.name}\n')
with tarfile.open(artifact) as tar:
    jar_sha = hashlib.sha256(tar.extractfile('apalache/lib/apalache.jar').read()).hexdigest()
(out / 'build-info.json').write_text(json.dumps({
    'apalache_commit': '7954daf7563a69cce9d0b89c8542e40bf46f7c6e',
    'grpc': '1.75.0', 'protobuf': '3.25.8', 'scalapb': '0.11.20',
    'artifact': artifact.name, 'sha256': sha, 'jar_sha256': jar_sha,
}, indent=2) + '\n')
print((out / 'SHA256SUMS').read_text(), end='')
print(f'{jar_sha}  apalache/lib/apalache.jar')
PY
