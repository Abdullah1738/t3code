"""subiquity_check.py: validate the stick's autoinstall config with the installer's own code.

Runs under the Python and the subiquity/curtin packages unpacked from the ISO (static-check.sh sets that up):
  1. subiquity's autoinstall JSON schema (generated by subiquity.cmd.schema, as the installer does) against
     the `autoinstall:` section of stick/nocloud/user-data, and against the same file with each storage
     section plan.py can generate (full install, REINSTALL-OS);
  2. curtin's storage schema (version 2, as subiquity passes it on) against those two generated sections.

  python3.10 subiquity_check.py USER_DATA STORAGE_JSON     (STORAGE_JSON = test_plan.py --dump-storage)
"""
import copy
import io
import json
import sys
from contextlib import redirect_stdout

import jsonschema
import yaml


def main():
    user_data, storage_json = sys.argv[1], sys.argv[2]
    doc = yaml.safe_load(open(user_data))
    ai = doc["autoinstall"]
    storages = json.load(open(storage_json))

    from subiquity.cmd import schema as schema_cmd

    buf = io.StringIO()
    argv, sys.argv = sys.argv, ["schema"]
    try:
        with redirect_stdout(buf):
            schema_cmd.main()
    finally:
        sys.argv = argv
    schema = json.loads(buf.getvalue())
    props = sorted(schema.get("properties", {}))
    unknown = sorted(set(ai) - set(props))
    if unknown:
        print(f"FAIL autoinstall keys subiquity does not know: {unknown}")
        return 1
    jsonschema.validate(ai, schema)
    print(f"ok   subiquity autoinstall schema: stick/nocloud/user-data ({len(ai)} sections, schema has {len(props)})")
    for name, st in storages.items():
        v = copy.deepcopy(ai)
        v["storage"] = st
        jsonschema.validate(v, schema)
        print(f"ok   subiquity autoinstall schema: user-data with the generated '{name}' storage section")

    import inspect

    from curtin import storage_config
    from curtin.commands import block_meta_v2

    # The installer hands curtin a version 2 storage config. block_meta_v2 consumes `partition_name`, but the
    # static schema of this curtin does not list the key (the real run does not apply that schema, C1 proves
    # the config installs). So: require that block_meta_v2 really reads the key, then validate the rest strictly.
    v2_reads_name = "partition_name" in inspect.getsource(block_meta_v2)
    if not v2_reads_name:
        print("FAIL curtin's block_meta_v2 does not read 'partition_name': the GPT names would not be set")
        return 1
    print("ok   curtin block_meta_v2 reads 'partition_name' (the key is absent from curtin's static schema)")
    for name, st in storages.items():
        items = [{k: v for k, v in item.items() if k != "partition_name"} for item in st["config"]]
        for item in items:
            if item.get("size") == -1:
                # subiquity's "rest of the disk"; it hands curtin the real number (C1: 1836114247680)
                item["size"] = 1836114247680
        cfg = {"storage": {"version": 2, "config": items}}
        storage_config.validate_config(cfg["storage"])
        print(f"ok   curtin storage schema (v2): generated '{name}' storage config ({len(items)} items)")
        tree = storage_config.extract_storage_ordered_dict(cfg)
        print(f"ok   curtin dependency order resolves: '{name}' ({len(tree)} items)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
