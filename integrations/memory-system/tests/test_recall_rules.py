class RuleIndexTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.fixture = RulesFixture(self.root)

    def tearDown(self):
        self.temp.cleanup()

    def conflict(self, index, command, cwd=None):
        cwd = cwd or self.fixture.cwd
        args = {"command": command}
        rules = index.applicable(cwd, "shell", args)
        return evaluate_conflict(rules, "shell", args, cwd)

    def test_existing_corpus_blocks_main_without_remember(self):
        index = self.fixture.index()
        result = self.conflict(index, "git push origin HEAD:main")
        self.assertEqual("deny", result["decision"])
        self.assertIn("push to main-dev", result["reason"])
        self.assertIn(str(self.fixture.skill) + "#L7", result["reason"])
        self.assertIn("Crpko services deploy always from `main-dev`, never `main`.", result["reason"])
        self.assertIsNone(self.conflict(index, "git push origin HEAD:main-dev"))
        self.assertIsNone(self.conflict(index, "git status"))
        self.assertEqual([], index.applicable(self.fixture.cwd, "shell", {"command": "git status"}))
        clone = "/private/var/folders/fixture/opencode/acceptance/trading-core"
        self.assertEqual("deny", self.conflict(index, "git push origin HEAD:main", clone)["decision"])
        self.assertIsNone(self.conflict(index, "git push origin HEAD:main", "/work/personal"))
        self.assertIsNotNone(self.conflict(index, "git push origin HEAD:main", self.fixture.cwd + "/src/engine"))

    def test_constraints_are_extracted_not_specific_to_main_dev(self):
        self.fixture.skill.write_text("# Crpko workflow\n\nCrpko services push only to `integration`, never `release`.\n")
        index = self.fixture.index()
        result = self.conflict(index, "git push origin HEAD:release")
        self.assertIn("push to integration", result["reason"])
        self.assertIsNone(self.conflict(index, "git push origin HEAD:main"))

    def test_numbered_skill_law_keeps_exact_multiline_citation(self):
        self.fixture.skill.write_text(
            "# crpko-review-workflow\n\n## Laws\n\n"
            "11. Deploy each repo after its last ready merge, always from `main-dev`,\n"
            "    never `main`.\n"
        )
        index = self.fixture.index()
        result = self.conflict(index, "git push origin HEAD:main")
        self.assertIn("#L5-L6", result["reason"])
        self.assertIn("push to main-dev", result["reason"])

    def test_scoped_agents_file_and_edit_reimport_remove_old_rule(self):
        project = self.root / "repo"
        project.mkdir()
        agents = project / "AGENTS.md"
        agents.write_text("# Rules\n\nAlways push to topic, never trunk.\n")
        index = RuleIndex(self.root / "rules.sqlite")
        self.assertEqual(1, index.import_files([agents])["imported"])
        self.assertEqual(1, index.import_files([agents])["unchanged"])
        self.assertIsNotNone(self.conflict(index, "git push origin HEAD:trunk", str(project / "sub")))
        self.assertIsNone(self.conflict(index, "git push origin HEAD:trunk", str(project) + "-other"))
        agents.write_text("# Rules\n\nKeep comments short.\n")
        index.import_files([agents])
        self.assertIsNone(self.conflict(index, "git push origin HEAD:trunk", str(project)))

    def test_explicit_remember_lifecycle_and_dedup(self):
        index = RuleIndex(self.root / "rules.sqlite")
        rule = index.remember("Remember this next time: when messaging Moni, keep it short.",
                              actions=["message"], recipient="Moni", source_session="ses_owner", source_event=42)
        self.assertEqual("ses_owner#e42", rule["citation"])
        self.assertEqual("explicit", rule["provenance"])
        self.assertEqual(100, rule["priority"])
        again = index.remember(rule["text"], actions=["message"], recipient="Moni", source_session="ses_owner", source_event=42)
        self.assertEqual(rule["id"], again["id"])
        reopened = RuleIndex(index.path)
        relevant = reopened.applicable("/work/other", "whatsapp.send", {"recipient": "Moni", "text": "hi"})
        self.assertEqual([rule["id"]], [r["id"] for r in relevant])
        self.assertEqual([], reopened.applicable("/work/other", "whatsapp.send", {"recipient": "David"}))
        self.assertEqual(rule["text"], relevant[0]["triggers"]["text"])

    def test_recipient_trigger_matches_unknown_action_before_classifier(self):
        index = RuleIndex(self.root / "rules.sqlite")
        saved = index.remember("When messaging Moni, never say as requested.", actions=["message"],
                               recipient="Moni", source_session="owner")
        rules = index.applicable("/work", "unknown_action", {"recipient": "Moni", "text": "hello"})
        self.assertEqual([saved["id"]], [rule["id"] for rule in rules])
        self.assertEqual("owner", rules[0]["citation"])
        self.assertEqual([], index.applicable("/work", "unknown_action", {"recipient": "David", "text": "hello"}))
        self.assertEqual([], index.applicable("/work", "unknown_action", {"recipient": "Monika", "text": "hello"}))
        index.remember("When messaging Mary Smith, keep it brief.", actions=["message"], recipient="Mary Smith",
                       scope="/project", source_session="owner")
        self.assertEqual(1, len(index.applicable("/project", "unknown_action", {"recipient": "mary smith"})))
        self.assertEqual([], index.applicable("/other", "unknown_action", {"recipient": "mary smith"}))

    def test_oversized_source_block_is_skipped_not_truncated_into_a_rule(self):
        self.fixture.style.write_text("# Writing\n\nNever " + "x" * 65536)
        index = RuleIndex(self.root / "rules.sqlite")
        stats = index.import_files([self.fixture.style])
        self.assertEqual(1, stats["oversized"])
        self.assertEqual([], index.applicable("/work", "", {}))

    def test_transcripts_accept_only_explicit_owner_corrections(self):
        index = self.fixture.index()
        with closing(sqlite3.connect(index.path)) as con:
            rules = con.execute("SELECT s.provenance,r.text,s.citation FROM rules r JOIN rule_sources s ON s.rule_id=r.id "
                                "WHERE s.provenance='owner_correction'").fetchall()
        self.assertEqual(1, len(rules), rules)
        self.assertEqual("ses_style#e4", rules[0][2])
        self.assertIn("one sentence", rules[0][1])
        # The assistant's unconfirmed proposal must not countermand the skill.
        self.assertIsNone(self.conflict(index, "git push origin HEAD:main-dev"))

    def test_transcript_cursor_is_durable_bounded_and_read_only(self):
        index = RuleIndex(self.root / "rules.sqlite")
        before = self.fixture.db.read_bytes()
        one = index.import_transcripts(self.fixture.db, max_rows=3)
        self.assertEqual((3, 3, False), (one["rows"], one["cursor"], one["complete"]))
        index = RuleIndex(index.path)
        two = index.import_transcripts(self.fixture.db, max_rows=2)
        self.assertEqual((2, 5, 1), (two["rows"], two["cursor"], two["imported"]))
        three = index.import_transcripts(self.fixture.db, max_rows=100)
        self.assertTrue(three["complete"])
        self.assertEqual(0, index.import_transcripts(self.fixture.db)["rows"])
        self.assertEqual(before, self.fixture.db.read_bytes())
        zero = index.import_transcripts(self.fixture.db, seconds=0)
        self.assertEqual(0, zero["rows"])

    def test_transcript_replacement_resets_cursor_and_new_rows_resume(self):
        index = self.fixture.index()
        with closing(sqlite3.connect(self.fixture.db)) as con, con:
            con.execute("INSERT INTO episodic_events VALUES(20,'ses_later',1700000020,'user','text',?,'{}')",
                        ("Next time use plain comments.",))
        self.assertEqual(1, index.import_transcripts(self.fixture.db)["imported"])
        replacement = self.root / "replacement.sqlite"
        with closing(sqlite3.connect(self.fixture.db)) as source, closing(sqlite3.connect(replacement)) as dest:
            source.backup(dest)
        replacement.replace(self.fixture.db)
        resumed = index.import_transcripts(self.fixture.db, max_rows=1)
        self.assertEqual((1, 1), (resumed["rows"], resumed["cursor"]))

    def test_lookup_never_reopens_corpus_and_first_compaction_restore_scope(self):
        index = self.fixture.index()
        self.fixture.db.unlink()
        self.fixture.skill.unlink()
        with patch.object(Path, "read_text", side_effect=AssertionError("request must not open source files")):
            records = index.applicable(self.fixture.cwd, "", {})
            self.assertTrue(any(r["scope"] == "crpko" for r in records))
            other = index.applicable("/work/other", "", {})
            self.assertFalse(any(r["scope"] == "crpko" for r in other))
            self.assertIsNotNone(self.conflict(index, "git push origin HEAD:main"))

    def test_relevant_rules_override_local_tool_classification_without_hype(self):
        index = self.fixture.index()
        rules = index.applicable("/work/personal", "patch", {"patchText": "*** Add File: docs/intro.md\n+text"})
        self.assertTrue(any("No AI markers anywhere" in r["text"] for r in rules))
        self.assertTrue(any("file.write" in r["actions"] for r in rules))
        self.assertEqual([], index.applicable("/work/personal", "read", {"path": "docs/intro.md"}))
        self.assertIsNone(evaluate_conflict(rules, "patch", {"patchText": "+text"}, "/work/personal"))

    def test_duplicate_files_retain_citations_but_not_duplicate_rules(self):
        index = RuleIndex(self.root / "rules.sqlite")
        second = self.root / "skills/style-copy/SKILL.md"
        second.parent.mkdir(parents=True)
        second.write_text(self.fixture.style.read_text())
        index.import_files([self.fixture.style, second])
        records = index.applicable("/work", "patch", {})
        self.assertEqual(1, len(records))
        self.assertEqual(2, len(records[0]["citations"]))

    def test_source_priority_prevents_false_deny_from_superseded_constraint(self):
        index = self.fixture.index()
